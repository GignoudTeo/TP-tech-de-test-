def test_triangulation_3points_reussi():
    point_set_bytes = (
        b"\x00\x00\x00\x03"  # 3 points
        b"\x00\x00\x00\x00\x00\x00\x00\x00"  # (0.0, 0.0)
        b"\x3f\x80\x00\x00\x00\x00\x00\x00"  # (1.0, 0.0)
        b"\x00\x00\x00\x00\x3f\x80\x00\x00"  # (0.0, 1.0)
    )
    assert triangulation(point_set_bytes) == ( b"\x00\x00\x00\x03" b"\x00\x00\x00\x00\x00\x00\x00\x00" b"\x3f\x80\x00\x00\x00\x00\x00\x00" b"\x00\x00\x00\x00\x3f\x80\x00\x00"  b"\x00\x00\x00\x01" b"\x00\x00\x00\x00"  b"\x00\x00\x00\x01"  b"\x00\x00\x00\x02" )
